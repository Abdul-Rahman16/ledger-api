import io
import json
import uuid

import pandas as pd
from sqlalchemy.orm import Session

from core.logging import log
from domain.models import Dataset, DatasetColumn
from domain.profiling import clean_dataframe, profile_dataframe, quality_score

MAX_UPLOAD_BYTES = 5 * 1024 * 1024
MAX_ROWS = 100_000
MAX_COLUMNS = 100
SUPPORTED_TYPES = {"csv": "csv", "xlsx": "excel", "json": "json"}


class IngestionError(Exception):
    """A problem with the uploaded file itself (safe to show the user)."""


def read_upload(filename: str, content: bytes) -> tuple[pd.DataFrame, str]:
    if len(content) == 0:
        raise IngestionError("The uploaded file is empty.")
    if len(content) > MAX_UPLOAD_BYTES:
        raise IngestionError(f"File is larger than the {MAX_UPLOAD_BYTES // (1024 * 1024)} MB limit.")

    extension = filename.rsplit(".", 1)[-1].lower() if "." in filename else ""
    source_type = SUPPORTED_TYPES.get(extension)
    if source_type is None:
        raise IngestionError(f"Unsupported file type '.{extension}'. Use CSV, XLSX, or JSON.")

    try:
        if source_type == "csv":
            df = pd.read_csv(io.BytesIO(content))
        elif source_type == "excel":
            df = pd.read_excel(io.BytesIO(content))
        else:
            df = pd.json_normalize(json.loads(content))
    except Exception as exc:
        raise IngestionError(f"Could not parse the file as {source_type}: {str(exc)[:200]}") from exc

    if len(df) > MAX_ROWS:
        raise IngestionError(f"File has {len(df)} rows; the limit is {MAX_ROWS}.")
    if len(df.columns) > MAX_COLUMNS:
        raise IngestionError(f"File has {len(df.columns)} columns; the limit is {MAX_COLUMNS}.")
    return df, source_type


def ingest_dataset(db: Session, filename: str, content: bytes, user_id: str | None = None) -> Dataset:
    raw_df, source_type = read_upload(filename, content)
    clean_df, report = clean_dataframe(raw_df)
    if clean_df.empty or len(clean_df.columns) == 0:
        raise IngestionError("The file contains no usable data after cleaning.")

    columns = profile_dataframe(clean_df)
    score = quality_score(columns, report["duplicate_rows_removed"], report["original_rows"])

    dataset_id = uuid.uuid4()
    table_name = f"ds_{dataset_id.hex}"  # generated by the server, never from user input
    dataset = Dataset(
        id=dataset_id,
        user_id=user_id,
        name=filename.rsplit(".", 1)[0][:100],
        source_type=source_type,
        original_filename=filename[:255],
        table_name=table_name,
        status="uploaded",
    )
    db.add(dataset)
    db.commit()

    try:
        clean_df.to_sql(table_name, con=db.connection(), index=False, if_exists="fail", chunksize=1000)
        dataset.row_count = len(clean_df)
        dataset.column_count = len(clean_df.columns)
        dataset.quality_score = score
        for column in columns:
            db.add(DatasetColumn(dataset_id=dataset_id, **column))
        dataset.status = "ready"
        db.commit()
    except Exception:
        db.rollback()
        failed = db.get(Dataset, dataset_id)
        failed.status = "failed"
        db.commit()
        log.error("dataset_ingestion_failed", dataset_id=str(dataset_id))
        raise

    log.info("dataset_ingested", dataset_id=str(dataset_id), rows=len(clean_df), quality_score=score)
    db.refresh(dataset)
    return dataset